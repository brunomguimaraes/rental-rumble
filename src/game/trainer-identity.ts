export type TrainerPortrait = (typeof TRAINER_PORTRAITS)[number];
export type TrainerPortraitId = TrainerPortrait['id'];
export type PortraitStyle = TrainerPortrait['gender'];
export const DEFAULT_PORTRAIT_ID: TrainerPortraitId = 'm01';
export const TRAINER_NAME_MAX = 24;

export interface TrainerIdentity {
  displayName: string;
  avatarId: TrainerPortraitId;
  colors: TrainerColors;
}

export function findTrainerPortrait(id: unknown): TrainerPortrait | undefined {
  return TRAINER_PORTRAITS.find((portrait) => portrait.id === id);
}

export function cleanTrainerName(raw: unknown): string | null {
  if (typeof raw !== 'string') return null;
  const name = raw.trim();
  if (!name || name.length > TRAINER_NAME_MAX) return null;
  // eslint-disable-next-line no-control-regex
  if (/[\u0000-\u001f\u007f<>]/.test(name)) return null;
  return name;
}
